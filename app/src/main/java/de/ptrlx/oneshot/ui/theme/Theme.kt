/**
 * The app theme.
 *
 * Dynamic colour is deliberately not used: the amber palette is the brand, and the film surfaces
 * are drawn against it. It can be added later behind a setting without touching this scheme.
 */
@Composable
fun OneShotTheme(darkTheme: Boolean = isSystemInDarkTheme(), content: @Composable () -> Unit) {
    MaterialTheme(
        colorScheme = if (darkTheme) DarkColors else LightColors,
        typography = Typography,
        shapes = Shapes,
        content = content
    )
}
